"""Build kaggle/zoha_web_teacher.ipynb from web_teacher_src.py, embedding Zoha's checker, starter and skill."""
import ast, json, re, uuid
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
tools = (ROOT / "zoha" / "tools.py").read_text(encoding="utf-8")
tree = ast.parse(tools)
funcs = {n.name: ast.get_source_segment(tools, n) for n in tree.body if isinstance(n, ast.FunctionDef)}
assigns = {t.id: ast.get_source_segment(tools, n) for n in tree.body if isinstance(n, ast.Assign) for t in n.targets if isinstance(t, ast.Name)}
NEED_F = ["_lum", "_contrast", "_mix", "_fix_contrast", "_add_motion", "_head_upgrades", "strip_layers", "final_cleanup", "lint_html", "autofix_html"]
NEED_A = ["MOTION_CSS", "MOTION_JS"]
LINT = ("import re\nimport datetime as dt\n\n\n" + "\n\n\n".join(assigns[a] for a in NEED_A) + "\n\n\n"
        + "\n\n\n".join(funcs[f] for f in NEED_F) + "\n").replace("from .web3d import", "from web3d import")
embed = {
    "PAGE_CHECK_SRC": (ROOT / "zoha" / "page_check.py").read_text(encoding="utf-8"),
    "LINT_SRC": LINT,
    "WEB_KIT_SRC": (ROOT / "zoha" / "web_kit.py").read_text(encoding="utf-8").replace("from .web3d import", "from web3d import")
                   .replace("from .web_showroom import", "from web_showroom import"),
    "WEB_SHOWROOM_SRC": (ROOT / "zoha" / "web_showroom.py").read_text(encoding="utf-8"),
    "WEB3D_SRC": (ROOT / "zoha" / "web3d.py").read_text(encoding="utf-8"),
    "STARTER_SRC": (ROOT / "skills" / "web-starter.html").read_text(encoding="utf-8"),
    "SKILL_SRC": re.sub(r"\A---\s*\n.*?\n---\s*\n", "", (ROOT / "skills" / "web-page.md").read_text(encoding="utf-8"), count=1, flags=re.S).lstrip(),
    "SHORT_PROMPT_SRC": (ROOT / "skills" / "web-short-prompt.txt").read_text(encoding="utf-8"),
}
src = (ROOT / "kaggle" / "web_teacher_src.py").read_text(encoding="utf-8")
emb_cell = "# %%\n# ── Zoha's checker, starter page and skill (embedded – generated by build_web_nb.py) ──\n" + \
           "\n".join(f"{k} = {json.dumps(v, ensure_ascii=False)}" for k, v in embed.items()) + "\n\n"
i = src.index("# %%\n# ── browser for testing pages")
src = src[:i] + emb_cell + src[i:]
(ROOT / "kaggle" / "web_teacher_full.py").write_text(src, encoding="utf-8")
parts = re.split(r"^# %%(.*)$", src, flags=re.M)
cells = []
for j in range(1, len(parts), 2):
    kind, body = parts[j].strip(), parts[j + 1].strip("\n")
    if kind == "[markdown]":
        cells.append({"cell_type": "markdown", "id": uuid.uuid4().hex[:8], "metadata": {},
                      "source": "\n".join(re.sub(r"^# ?", "", l) for l in body.split("\n"))})
    else:
        compile(body, "cell", "exec")
        cells.append({"cell_type": "code", "id": uuid.uuid4().hex[:8], "metadata": {}, "execution_count": None,
                      "outputs": [], "source": body})
md = {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}, "language_info": {"name": "python"},
      "kaggle": {"accelerator": "nvidiaTeslaT4", "isInternetEnabled": True, "isGpuEnabled": True}}
(ROOT / "kaggle" / "zoha_web_teacher.ipynb").write_text(json.dumps({"cells": cells, "metadata": md, "nbformat": 4, "nbformat_minor": 5}, indent=1), encoding="utf-8")
print("built", len(cells), "cells")
